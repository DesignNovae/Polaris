/** Verify the supplied originals and extract their GalleryHeading dependency closure.
 * Source declarations and renderer strings are copied verbatim, not rewritten.
 * Next.js consumes raw HTML through a generated JSON string instead of Vite ?raw.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import ts from "typescript";

const root = new URL("../vendor/threeui-gallery/", import.meta.url);
const output = new URL("../components/threeui/", import.meta.url);
const check = process.argv.includes("--check");
const hashes = {
  "src/shaders/neuform-isolated/NeuformIsolatedEffects.tsx": "fe9856234253bc3c1a13b3afb84f3d84644dfa6d578e7203bb3e1dd5eced1b75",
  "src/shaders/neuform-isolated/sources/gallery-heading.html": "8e42d2d5b4971bfc4d3c485112c3c51909e20a61b8842bc0dcd8db3ffe2d253a",
  "src/shaders/threeui.css": "efe4447139f1358dd8e9be68edf6fa46cbefbd1de423a4d6c439ca61d2c8eccf",
};
const sources = {};
for (const [path, hash] of Object.entries(hashes)) {
  const bytes = readFileSync(new URL(path, root));
  if (createHash("sha256").update(bytes).digest("hex") !== hash) throw new Error(`Source hash mismatch: ${path}`);
  sources[path] = bytes.toString("utf8");
}
const source = sources[Object.keys(hashes)[0]];
const ast = ts.createSourceFile("NeuformIsolatedEffects.tsx", source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
const declarations = new Map();
for (const statement of ast.statements) {
  if (ts.isVariableStatement(statement)) {
    for (const declaration of statement.declarationList.declarations) {
      if (ts.isIdentifier(declaration.name)) declarations.set(declaration.name.text, statement);
    }
  } else if (statement.name && ts.isIdentifier(statement.name)) declarations.set(statement.name.text, statement);
}
const effects = declarations.get("EFFECTS");
let initializer = effects.declarationList.declarations[0].initializer;
while (ts.isAsExpression(initializer) || ts.isSatisfiesExpression(initializer)) initializer = initializer.expression;
const gallery = initializer.properties.find(p => p.name?.getText(ast) === "galleryHeading");
if (!gallery) throw new Error("Missing authored GalleryHeading definition");
const selected = new Set();
function include(name) {
  const node = declarations.get(name);
  if (!node || selected.has(node)) return;
  selected.add(node);
  function walk(child) {
    if (ts.isIdentifier(child)) include(child.text);
    ts.forEachChild(child, walk);
  }
  walk(name === "EFFECTS" ? gallery : node);
}
include("GalleryHeading");
include("EffectDefinition");
const blocks = ast.statements.filter(s => selected.has(s)).map(s => s === effects
  ? `const EFFECTS = {\n  ${gallery.getText(ast)}\n} as const satisfies Record<string, EffectDefinition>;`
  : s.getText(ast));
const generated = '"use client";\n\n// Generated by scripts/sync-threeui-gallery.mjs. Do not hand-edit.\n'
  + 'import { useEffect, useMemo, useRef, type CSSProperties } from "react";\n'
  + 'import galleryHeadingSource from "./gallery-heading.source.json";\n\n'
  + blocks.join("\n\n") + "\n"
  + '\n// Extension points for the separate Polaris customization.\n'
  + 'export { NeuformIsolatedEffect, transformGalleryHeadingSource, EFFECTS };\n'
  + 'export type { EffectDefinition };\n';
function emit(url, content) {
  if (check) {
    if (readFileSync(url, "utf8") !== content) throw new Error(`Generated source drift: ${url.pathname}`);
  } else writeFileSync(url, content);
}
mkdirSync(output, { recursive: true });
emit(new URL("GalleryHeading.generated.tsx", output), generated);
emit(new URL("gallery-heading.source.json", output), JSON.stringify(sources[Object.keys(hashes)[1]]) + "\n");
const publicStyles = new URL("../public/threeui/", import.meta.url);
mkdirSync(publicStyles, { recursive: true });
emit(new URL("threeui.css", publicStyles), sources[Object.keys(hashes)[2]]);
console.log(`Verified 3 original SHA-256 hashes; ${selected.size} source declarations ${check ? "checked" : "extracted verbatim"}.`);
