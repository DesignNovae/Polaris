function dynamicBengali(text: string): string {
  return text
    .replace(
      /^(\d+)-day plan\s*·\s*(\d+)\s+yearly phases?\s*·\s*(\d+)\/(\d+)\s+missions? done$/i,
      (_m, days, phases, complete, total) =>
        `${toBengaliDigits(days)} দিনের প্ল্যান · ${toBengaliDigits(phases)}টি বার্ষিক ধাপ · ${toBengaliDigits(complete)}/${toBengaliDigits(total)}টি মিশন সম্পন্ন`,
    )
    .replace(
      /^Current focus:\s*"(.+)"\s*\((.+)\)\.\s*Done when:\s*(.+)$/i,
      (_m, title, category, criteria) =>
        `বর্তমান মনোযোগ: “${translateUiText(title)}” (${translateUiText(category)})। সম্পন্ন হবে যখন: ${translateUiText(criteria)}`,
    )
    .replace(/^(\d+)\s+live deadlines?$/i, (_m, n) => `${toBengaliDigits(n)}টি সক্রিয় সময়সীমা`)
    .replace(/^(\d+)\s+deadlines?$/i, (_m, n) => `${toBengaliDigits(n)}টি সময়সীমা`)
    .replace(/^(\d+)\s+open items?$/i, (_m, n) => `${toBengaliDigits(n)}টি খোলা কাজ`)
    .replace(/^(\d+)\s+urgent$/i, (_m, n) => `${toBengaliDigits(n)}টি জরুরি`)
    .replace(/^Next\s+(\d+)\s+days$/i, (_m, n) => `পরবর্তী ${toBengaliDigits(n)} দিন`)
    .replace(/^Year\s+(\d+)$/i, (_m, n) => `${toBengaliDigits(n)}ম বছর`)
    .replace(/^Step\s+(\d+)\s+of\s+(\d+)$/i, (_m, a, b) => `ধাপ ${toBengaliDigits(a)} / ${toBengaliDigits(b)}`)
    .replace(/^(\d+)%\s+grown$/i, (_m, n) => `${toBengaliDigits(n)}% উন্নতি`)
    .replace(/^(\d+)\s+days remaining$/i, (_m, n) => `${toBengaliDigits(n)} দিন বাকি`)
    .replace(/^(\d+)\s+yearly phases?$/i, (_m, n) => `${toBengaliDigits(n)}টি বার্ষিক ধাপ`)
    .replace(/^(\d+)\/(\d+)\s+missions done$/i, (_m, a, b) => `${toBengaliDigits(a)}/${toBengaliDigits(b)}টি মিশন সম্পন্ন`)
    .replace(/^(\d+)-day plan$/i, (_m, n) => `${toBengaliDigits(n)} দিনের প্ল্যান`)
    .replace(/^(\d+)%\s+complete$/i, (_m, n) => `${toBengaliDigits(n)}% সম্পন্ন`)
    .replace(/^(\d+)\s+facts?$/i, (_m, n) => `${toBengaliDigits(n)}টি তথ্য`)
    .replace(/^(\d+)\s+new signals?$/i, (_m, n) => `${toBengaliDigits(n)}টি নতুন সংকেত`);
}

export function translateUiText(value: string): string {
  if (!value || !/[A-Za-z0-9]/.test(value)) return value;

  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  const text = value.trim();
  if (!text) return value;
  const calendarWord = MONTHS[text] ?? DAYS[text];
  if (calendarWord) {
    return `${leading}${calendarWord}${trailing}`;
  }
  if (PROTECTED.test(text) || /^(?:https?:\/\/|mailto:|[\w.+-]+@[\w.-]+\.)/i.test(text)) {
    return value;
  }

  const exact = BN_JUDGE_WORKSPACE[text] ?? BN_LANDING[text] ?? BN_UI[text] ?? BN_UI_SECONDARY[text] ?? BN_REVIEWED_OVERRIDES[text];
  if (exact) return `${leading}${toBengaliDigits(exact)}${trailing}`;

  const translated = dynamicBengali(text);
  if (translated !== text) return `${leading}${translated}${trailing}`;

  const generated = BN_PRETRANSLATED[text];
  if (generated) {
    return `${leading}${toBengaliDigits(generated)}${trailing}`;
  }

  // Legacy lexical rules are safe only when they translate the complete
  // value. Applying them inside a sentence creates broken hybrid copy.
  for (const [pattern, replacement] of [...PHRASE_RULES, ...WORD_RULES]) {
    const candidate = text.replace(pattern, replacement);
    if (candidate !== text && !/[A-Za-z]/.test(candidate)) {
      return `${leading}${toBengaliDigits(candidate)}${trailing}`;
    }
  }

  // Keep new, uncatalogued copy intact instead of producing a partial,
  // ungrammatical Bengali-English sentence.
  return value;
}

export function formatLocaleNumber(
  value: number,
  lang: "en" | "bn",
  options?: Intl.NumberFormatOptions,
): string {
  return new Intl.NumberFormat(lang === "bn" ? "bn-BD" : "en-US", options).format(value);
}

export function formatLocaleDate(
  value: Date | string | number,
  lang: "en" | "bn",
  options: Intl.DateTimeFormatOptions = { year: "numeric", month: "long", day: "numeric" },
): string {
  return new Intl.DateTimeFormat(lang === "bn" ? "bn-BD" : "en-US", options).format(new Date(value));
}
