"""Pre-generate ASL motion for the catalogue lessons and IELTS Listening parts on a local GPU.

Only the GPU stage runs here. Each eight-second section is saved as the joined pose
streams the live worker would produce (same transcription, seed, and boundary join),
so the licensed SMPL-X mesh is not needed on this machine. Meshes are built later
from these poses wherever the licensed file lives.

Run from the project root, after the install steps in docs/SIGN_LANGUAGE_PRODUCTION.md:

    .cache/signing/venv/Scripts/python.exe services/signing/pregenerate.py

Interrupt with Ctrl+C at any time; rerunning resumes at the first missing section.
When it finishes, zip the output folder (.cache/signing/pregenerated by default) and send it.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
import time

ROOT = Path(__file__).resolve().parents[2]
FORMAT = "polaris-pregenerated-motion/1"


def targets():
    """Exam parts first (short), then guided-path lessons, then the rest by length."""
    catalogue = json.loads((ROOT / "data/learning/catalog.json").read_text(encoding="utf-8"))
    paths = (ROOT / "lib/learning/catalog.ts").read_text(encoding="utf-8")
    exam = [{"id": f"exam-ielts-listening-{part}", "kind": "exam", "part": part, "title": f"IELTS Listening {part}",
             "source": ROOT / "assets/exams/ielts-listening" / f"{part}.wav", "durationSeconds": 25}
            for part in ("part-1", "part-2", "part-3", "part-4")]
    lessons = [{"id": video["id"], "kind": "lesson", "youtubeId": video["youtubeId"], "title": video["title"],
                "durationSeconds": video.get("durationSeconds") or 0} for video in catalogue if video.get("youtubeId")]
    lessons.sort(key=lambda video: (f'"{video["id"]}"' not in paths, video["durationSeconds"]))
    return exam + lessons


def section_valid(path):
    import numpy as np
    try:
        with np.load(path, allow_pickle=False) as values:
            return all(name in values.files for name in ("hand", "body", "face", "start", "end"))
    except Exception:
        return False


def source_for(target, sources):
    from media import download_youtube
    if target["kind"] == "exam":
        return target["source"]
    directory = sources / target["id"]
    existing = [path for path in directory.glob("source.*") if path.suffix not in (".part", ".ytdl")] if directory.is_dir() else []
    if existing:
        return existing[0]
    directory.mkdir(parents=True, exist_ok=True)
    return download_youtube(target["youtubeId"], directory)


def to_device(array):
    import torch
    return torch.from_numpy(array).cuda()


def generate(pending, folder, source, duration, source_hash, engine, transcriber):
    """Batch the GPU stage one network at a time; results equal per-section live generation.

    The live worker keeps all three networks ready, which needs every 5.6 GB checkpoint
    mapped at once. Here each phase saves its results in folder/work, so only one
    checkpoint is open and one network is on the GPU, and an interrupted run resumes.
    """
    import numpy as np
    from engine import CHANNELS, join_motion_boundary, section_frames, section_seed, silence_streams
    work = folder / "work"
    work.mkdir(exist_ok=True)
    texts_path = work / "texts.json"
    texts = json.loads(texts_path.read_text(encoding="utf-8")) if texts_path.exists() else {}
    started = time.monotonic()
    for number, index in enumerate(pending, 1):
        if str(index) not in texts:
            texts[str(index)] = list(transcriber.transcribe(source, index, duration))
            texts_path.write_text(json.dumps(texts), encoding="utf-8")
        if number % 10 == 0 or number == len(pending):
            print(f"  transcribed {number}/{len(pending)} sections", flush=True)
    for index in pending:
        path = work / f"{index}.emb.npy"
        if texts[str(index)][0] and not path.exists():
            embedding = engine._text(texts[str(index)][0])
            np.save(path, np.asarray(embedding.cpu() if hasattr(embedding, "cpu") else embedding, dtype="float32"))
    engine.release(encoder=True)
    print(f"  encoded text ({time.monotonic() - started:.0f} s so far)", flush=True)
    spoken = [index for index in pending if texts[str(index)][0]]
    for offset, stream in enumerate(CHANNELS):
        stage = time.monotonic()
        for number, index in enumerate(spoken, 1):
            path = work / f"{index}.{stream}.npy"
            if path.exists():
                continue
            speech, start, end = texts[str(index)]
            motion = engine._sample(stream, to_device(np.load(work / f"{index}.emb.npy")), section_frames(end - start),
                                    section_seed(f"{source_hash}:{index}") + offset, lambda: False)
            np.save(path.with_suffix(".tmp.npy"), motion)
            path.with_suffix(".tmp.npy").replace(path)
            rate = (time.monotonic() - stage) / number
            print(f"  {stream} {number}/{len(spoken)}; ~{rate * (len(spoken) - number) / 60:.0f} min left for {stream}", flush=True)
        engine.release(stream)
    for index in pending:
        speech, start, end = texts[str(index)]
        streams = ({stream: np.load(work / f"{index}.{stream}.npy") for stream in CHANNELS} if speech
                   else silence_streams(section_frames(end - start)))
        previous = {}
        if (folder / f"{index - 1}.npz").is_file():
            with np.load(folder / f"{index - 1}.npz", allow_pickle=False) as values:
                previous = {stream: values[stream] for stream in CHANNELS}
        streams = join_motion_boundary(streams, previous)
        path = folder / f"{index}.npz"
        with path.with_suffix(".tmp").open("wb") as handle:
            np.savez_compressed(handle, **streams, start=np.float64(start), end=np.float64(end),
                                frames=np.int32(section_frames(end - start)), text=np.array(speech))
        path.with_suffix(".tmp").replace(path)
    shutil.rmtree(work, ignore_errors=True)
    print(f"  {len(pending)} sections done in {(time.monotonic() - started) / 60:.1f} min", flush=True)


def run(target, output, sources, engine, transcriber, steps):
    from engine import REVISION, SOURCE_REVISION
    from media import CHUNK_SECONDS, audio_duration
    folder = output / target["id"]
    folder.mkdir(parents=True, exist_ok=True)
    source = source_for(target, sources)
    duration = audio_duration(source)
    digest = hashlib.sha256()
    with Path(source).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    source_hash = digest.hexdigest()
    count = max(1, -(-int(duration * 1000) // int(CHUNK_SECONDS * 1000)))
    info = {"format": FORMAT, "id": target["id"], "kind": target["kind"], "title": target["title"],
            "youtubeId": target.get("youtubeId"), "part": target.get("part"), "duration": duration,
            "chunkSeconds": CHUNK_SECONDS, "sections": count, "sourceHash": source_hash, "steps": steps,
            "precision": engine.precision(),
            "modelRevision": REVISION, "sourceRevision": SOURCE_REVISION, "fps": 25, "language": "ase"}
    previous_info = folder / "source.json"
    if previous_info.exists():
        recorded = json.loads(previous_info.read_text(encoding="utf-8"))
        if any(recorded.get(key) != info[key] for key in ("sourceHash", "steps", "precision")):
            # A different recording, step count, or precision would make kept sections inconsistent with new ones.
            print(f"  source, step count, or precision changed; regenerating {target['id']} from the start", flush=True)
            for stale in folder.glob("*.npz"):
                stale.unlink()
            shutil.rmtree(folder / "work", ignore_errors=True)
    previous_info.write_text(json.dumps(info, indent=2), encoding="utf-8")
    pending = [index for index in range(count) if not section_valid(folder / f"{index}.npz")]
    if pending:
        generate(pending, folder, source, duration, source_hash, engine, transcriber)
    info["complete"] = all(section_valid(folder / f"{i}.npz") for i in range(count))
    previous_info.write_text(json.dumps(info, indent=2), encoding="utf-8")
    return info


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--output", type=Path, default=ROOT / ".cache/signing/pregenerated")
    parser.add_argument("--steps", type=int, default=50, help="Sampling steps: 50 = authors' setting (default), 10 = about 4x faster")
    parser.add_argument("--only", help="Comma-separated catalogue ids (see --list) to generate instead of everything")
    parser.add_argument("--exam-only", action="store_true", help="Generate only the four IELTS Listening parts")
    parser.add_argument("--max-minutes", type=float, help="Skip lessons longer than this")
    parser.add_argument("--list", action="store_true", help="Print the generation order and exit")
    args = parser.parse_args()
    if not 4 <= args.steps <= 50:
        parser.error("--steps must be between 4 and 50")
    # config() reads the step count from the environment on every section.
    os.environ["POLARIS_SIGNING_STEPS"] = str(args.steps)

    chosen = targets()
    if args.exam_only:
        chosen = [t for t in chosen if t["kind"] == "exam"]
    if args.only:
        wanted = {value.strip() for value in args.only.split(",") if value.strip()}
        unknown = wanted - {t["id"] for t in chosen}
        if unknown:
            parser.error("Unknown ids: " + ", ".join(sorted(unknown)) + ". Use --list to see valid ids.")
        chosen = [t for t in chosen if t["id"] in wanted]
    if args.max_minutes:
        chosen = [t for t in chosen if t["durationSeconds"] <= args.max_minutes * 60]
    total = sum(t["durationSeconds"] for t in chosen)
    if args.list:
        for t in chosen:
            print(f'{t["id"]:<32} {t["durationSeconds"] / 60:5.1f} min  {t["title"]}')
        print(f"{len(chosen)} items, {total / 3600:.1f} h of media")
        return

    from engine import SignEngine
    from media import Transcriber
    ready, message = SignEngine.motion_readiness()
    if not ready:
        sys.exit(f"{message}. Follow 'Install on another Windows machine' in docs/SIGN_LANGUAGE_PRODUCTION.md.")
    import torch
    if not torch.cuda.is_available():
        sys.exit("CUDA GPU unavailable. Install the NVIDIA driver and the CUDA PyTorch environment.")

    output, sources = args.output.resolve(), (ROOT / ".cache/signing/pregenerate-sources").resolve()
    output.mkdir(parents=True, exist_ok=True)
    print(f"{len(chosen)} items, {total / 3600:.1f} h of media at {args.steps} steps on {torch.cuda.get_device_name()}.\n"
          f"Roughly {total * (1.1 if args.steps >= 50 else 0.55) / 3600:.0f} h on an RTX 3070. Safe to stop and rerun.", flush=True)
    engine, transcriber = SignEngine(), Transcriber()
    manifest_path = output / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    for number, target in enumerate(chosen, 1):
        print(f"[{number}/{len(chosen)}] {target['id']}: {target['title']}", flush=True)
        try:
            info = run(target, output, sources, engine, transcriber, args.steps)
            manifest[target["id"]] = {"status": "complete" if info["complete"] else "partial", "sections": info["sections"]}
        except KeyboardInterrupt:
            print("\nStopped. Rerun the same command to continue.", flush=True)
            break
        except ValueError as error:
            # Expected per-video problems (YouTube refused audio, non-English speech): record and move on.
            print(f"  skipped: {error}", flush=True)
            manifest[target["id"]] = {"status": "failed", "reason": str(error)}
        finally:
            manifest_path.write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    done = [key for key, value in manifest.items() if value.get("status") == "complete"]
    failed = [key for key, value in manifest.items() if value.get("status") == "failed"]
    size = sum(path.stat().st_size for path in output.rglob("*.npz"))
    print(f"\n{len(done)} complete, {len(failed)} failed, {size / 1024 ** 2:.0f} MB in {output}")
    if failed:
        print("Failed: " + ", ".join(failed))
    print(f"Send this folder zipped: {output}\n(Downloaded audio in {sources} is not needed.)")


if __name__ == "__main__":
    main()
