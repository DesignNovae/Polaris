import json
import pytest

import numpy as np

import engine
import media
import pregenerate


class FakeEngine:
    """Deterministic stand-in for the GPU networks, recording what each was asked to sample."""

    def __init__(self):
        self.samples = []
        self.released = []

    def _text(self, text):
        return np.full((1, 4), len(text), dtype="float32")

    def _sample(self, stream, embedding, frames, seed, cancelled):
        self.samples.append((stream, seed))
        rng = np.random.default_rng(seed)
        return rng.normal(size=(2 if stream == "hand" else 1, frames, engine.CHANNELS[stream])).astype("float32")

    def release(self, stream=None, encoder=False):
        self.released.append(stream or "encoder")

    @staticmethod
    def precision():
        return "fp16"


class FakeTranscriber:
    def transcribe(self, path, index, duration):
        start = index * media.CHUNK_SECONDS
        return ("" if index == 1 else f"words {index}"), start, min(duration, start + media.CHUNK_SECONDS)


def target(tmp_path):
    source = tmp_path / "part-1.wav"
    source.write_bytes(b"audio")
    return {"id": "exam-ielts-listening-part-1", "kind": "exam", "part": "part-1", "title": "Part 1", "source": source}


def test_sections_use_live_seeds_join_boundaries_and_resume(tmp_path, monkeypatch):
    monkeypatch.setattr(media, "audio_duration", lambda _path: 20.0)
    monkeypatch.setattr(pregenerate, "to_device", lambda array: array)
    item, output = target(tmp_path), tmp_path / "out"
    first = FakeEngine()
    info = pregenerate.run(item, output, tmp_path / "sources", first, FakeTranscriber(), 50)
    assert info["complete"] and info["sections"] == 3
    # Section 1 is silent, so only 0 and 2 are sampled: every hand, then body, then face, each with live seeds.
    seeds = {i: engine.section_seed(f"{info['sourceHash']}:{i}") for i in (0, 2)}
    assert first.samples == [(stream, seeds[i] + offset) for offset, stream in enumerate(engine.CHANNELS) for i in (0, 2)]
    assert first.released == ["encoder", "hand", "body", "face"]
    folder = output / item["id"]
    assert not (folder / "work").exists()
    sections = []
    for i in range(3):
        with np.load(folder / f"{i}.npz") as values:
            sections.append({name: values[name] for name in values.files})
    for before, after in zip(sections, sections[1:]):
        for name in engine.CHANNELS:
            np.testing.assert_array_equal(after[name][:, 0], before[name][:, -1])
    assert str(sections[1]["text"]) == "" and float(sections[2]["end"]) == 20.0

    (folder / "2.npz").unlink()
    again = FakeEngine()
    assert pregenerate.run(item, output, tmp_path / "sources", again, FakeTranscriber(), 50)["complete"]
    assert [seed for _, seed in again.samples] == [seeds[2] + offset for offset in range(3)]


def test_changed_step_count_discards_inconsistent_sections(tmp_path, monkeypatch):
    monkeypatch.setattr(media, "audio_duration", lambda _path: 10.0)
    monkeypatch.setattr(pregenerate, "to_device", lambda array: array)
    item, output = target(tmp_path), tmp_path / "out"
    pregenerate.run(item, output, tmp_path / "sources", FakeEngine(), FakeTranscriber(), 50)
    rerun = FakeEngine()
    pregenerate.run(item, output, tmp_path / "sources", rerun, FakeTranscriber(), 10)
    assert len(rerun.samples) == 3  # section 0 regenerated by all three networks; section 1 is silent
    assert json.loads((output / item["id"] / "source.json").read_text())["steps"] == 10


def test_targets_cover_exam_parts_first_then_every_catalogue_lesson():
    items = pregenerate.targets()
    assert [t["kind"] for t in items[:4]] == ["exam"] * 4 and all(t["source"].is_file() for t in items[:4])
    lessons = [t for t in items if t["kind"] == "lesson"]
    assert len({t["id"] for t in lessons}) == len(lessons) and all(len(t["youtubeId"]) == 11 for t in lessons)


def test_batched_sections_equal_live_per_section_motion(tmp_path, monkeypatch):
    torch = pytest.importorskip("torch")
    if not torch.cuda.is_available():
        pytest.skip("engine.motion needs CUDA")
    fake = FakeEngine()
    live = engine.SignEngine()
    monkeypatch.setattr(engine.SignEngine, "motion_readiness", staticmethod(lambda: (True, "ready")))
    monkeypatch.setattr(live, "_text", fake._text)
    monkeypatch.setattr(live, "_sample", fake._sample)
    monkeypatch.setattr(media, "audio_duration", lambda _path: 20.0)
    monkeypatch.setattr(pregenerate, "to_device", lambda array: array)
    item, output = target(tmp_path), tmp_path / "out"
    info = pregenerate.run(item, output, tmp_path / "sources", FakeEngine(), FakeTranscriber(), 50)
    folder = output / item["id"]
    for index in range(3):
        speech, start, end = FakeTranscriber().transcribe(None, index, 20.0)
        expected, *_ = live.motion(speech, end - start, f"{info['sourceHash']}:{index}", previous_path=folder / f"{index - 1}.npz")
        with np.load(folder / f"{index}.npz") as values:
            for name in engine.CHANNELS:
                np.testing.assert_array_equal(values[name], expected[name])
